/**
 * HavaVerse Play — watch experience contract.
 *
 * The watch page is a DATA-PLANE surface. Everything that is a business
 * decision — prices, currency, entitlement, available languages, qualities,
 * support tiers — arrives as configuration from the control plane and is
 * never decided in a component.
 */

export type PlayerStatus =
'idle' |
'loading' |
'playing' |
'paused' |
'buffering' |
'seeking' |
'ended' |
'error';

/** Why a viewer can or cannot watch. Resolved server-side in production. */
export type EntitlementState =
'available' |
'premium-included' |
'ppv-required' |
'subscription-required' |
'region-restricted' |
'age-restricted' |
'unavailable' |
'processing';

export interface Entitlement {
  state: EntitlementState;
  /** Shown verbatim to the viewer. Never invent a reason client-side. */
  reason: string;
  /** Minor units (kobo). Only present when a purchase can unlock the title. */
  priceMinor?: number;
  /** e.g. 'Included with HavaVerse Premium' */
  includedWith?: string;
  availableRegions?: string[];
  minimumAge?: number;
}

export interface Chapter {
  id: string;
  label: string;
  startSeconds: number;
  /** Chapters generated by the Story Agent are labelled as such. */
  generated?: boolean;
  kind?: 'intro' | 'scene' | 'credits' | 'highlight';
  still?: string;
}

export interface QualityOption {
  id: string;
  label: string;
  height: number;
  /** Not every master exists at every rung — only offer what is encoded. */
  available: boolean;
}

export interface AudioTrack {
  id: string;
  label: string;
  /** Dubbed tracks are marked so a viewer knows what they are choosing. */
  kind: 'original' | 'dub' | 'described';
}

export interface SubtitleTrack {
  id: string;
  label: string;
  kind: 'subtitles' | 'captions';
}

export interface CastMember {
  id: string;
  name: string;
  role: string;
  portrait: string;
  to?: string;
}

export type GraphNodeKind = 'character' | 'location' | 'story' | 'soundtrack' | 'product';

export interface GraphNode {
  id: string;
  kind: GraphNodeKind;
  name: string;
  meta: string;
  image: string;
  /** Where the full entity lives, when one exists in the graph. */
  to?: string;
  /** Character-only detail, rendered in the contextual drawer. */
  bio?: string;
  appearsIn?: {label: string;to: string;}[];
}

export interface WatchComment {
  id: string;
  author: string;
  handle: string;
  avatar: string;
  body: string;
  postedAt: string;
  likes: number;
  /** Seconds into the title. Clicking seeks the player there. */
  atSeconds?: number;
  fromCreator?: boolean;
  replies: WatchComment[];
}

export type CommentSort = 'top' | 'newest' | 'discussed';

export interface SupportTier {
  id: string;
  minor: number;
  label: string;
}

/** Everything the control plane configures for the economy on this surface. */
export interface EconomyConfig {
  currency: string;
  currencySymbol: string;
  supportTiers: SupportTier[];
  /** Monetisation paths enabled for this creator. Absent = not offered. */
  enabled: ('tip' | 'membership' | 'merch' | 'ppv')[];
  membershipMinor?: number;
  membershipLabel?: string;
}

export interface AiAnswer {
  body: string;
  /** Graph entities the answer is grounded in. */
  citations?: {label: string;meta: string;to: string;image?: string;}[];
  seekTo?: number;
}

export interface WatchAsset {
  slug: string;
  durationSeconds: number;
  backdrop: string;
  entitlement: Entitlement;
  qualities: QualityOption[];
  audio: AudioTrack[];
  subtitles: SubtitleTrack[];
  chapters: Chapter[];
  cast: CastMember[];
  graph: GraphNode[];
  economy: EconomyConfig;
  /** Grounding for the companion. It answers from here or says it cannot. */
  knowledge: {match: string[];answer: AiAnswer;}[];
  suggestedQuestions: string[];
  discussionCount: string;
  likes: number;
  followers: string;
}

export interface ResumePoint {
  slug: string;
  positionSeconds: number;
  completion: number;
  updatedAt: number;
  device: string;
}

/** One continuous viewing of a title. History is a log of these, not one row per title. */
export interface WatchSession {
  id: string;
  slug: string;
  startedAt: number;
  endedAt: number;
  fromSeconds: number;
  toSeconds: number;
  /** Completion reached by the end of this session, 0–100. */
  completion: number;
  device: string;
}

export type TitleReaction = 'up' | 'down';

export interface TitleReactionRecord {
  slug: string;
  reaction: TitleReaction;
  at: number;
}

/** Meaningful playback milestones only — never a per-frame event stream. */
export type AnalyticsEvent =
'content_view' |
'play_started' |
'play_paused' |
'play_resumed' |
'play_completed' |
'seek' |
'quality_changed' |
'subtitle_changed' |
'audio_changed' |
'fullscreen_entered' |
'watchlist_added' |
'watchlist_removed' |
'like_added' |
'share_created' |
'comment_created' |
'watch_party_created' |
'creator_followed' |
'creator_supported' |
'ai_opened' |
'ai_question_asked' |
'recommendation_clicked' |
'report_created' |
'progress_25' |
'progress_50' |
'progress_75';

export interface AnalyticsRecord {
  id: string;
  event: AnalyticsEvent;
  slug: string;
  at: number;
  detail?: string;
}